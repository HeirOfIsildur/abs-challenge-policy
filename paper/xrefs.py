"""HONZA-92: plain-text cross-references between main.tex and supplement.tex.

imsart refuses xr/xr-hyper ("external references are not supported in our workflow"), so each document's labels are
read from its .aux and written as macros: generated/xref_main.tex (\\Mref{label}, used in supplement.tex) and
generated/xref_supp.tex (\\Sref{label}, used in main.tex). Both expand to plain numbers, survive `make submission`,
and an unknown label prints ?? and the warning "Reference `label' undefined", which `make check` catches.
usage (from paper/): python xrefs.py"""
import os, re

HEAD = r"""%% generated by paper/xrefs.py from {aux} -- do not edit
\makeatletter
\providecommand{{\{cmd}}}[1]{{\@ifundefined{{xr{tag}@#1}}{{\textbf{{??}}\PackageWarning{{xrefs}}{{Reference `#1' undefined}}}}{{\@nameuse{{xr{tag}@#1}}}}}}
"""


def labels(aux):
    out = {}
    if os.path.exists(aux):
        for line in open(aux, encoding="utf-8", errors="replace"):
            mt = re.match(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}", line)
            if mt and not mt.group(1).endswith("@cref"):
                out[mt.group(1)] = mt.group(2)
    return out


def write(aux, out, cmd, tag):
    L = [HEAD.format(aux=aux, cmd=cmd, tag=tag).rstrip("\n")]
    L += [f"\\@namedef{{xr{tag}@{k}}}{{{v}}}" for k, v in sorted(labels(aux).items())]
    L += ["\\makeatother"]
    text = "\n".join(L) + "\n"
    if not os.path.exists(out) or open(out).read() != text:      # leave the file untouched if nothing changed
        open(out, "w").write(text)


if __name__ == "__main__":
    os.makedirs("generated", exist_ok=True)
    write("main.aux", "generated/xref_main.tex", "Mref", "M")
    write("supplement.aux", "generated/xref_supp.tex", "Sref", "S")
