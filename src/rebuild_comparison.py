"""HONZA-88 before/after table: every macro the draft quotes (paper/generated/numbers.tex), pre-rebuild vs rebuilt,
flagging relative changes > 10 % (and sign flips).
usage: python src/rebuild_comparison.py <old numbers.tex> [new numbers.tex]  -> results/rebuild_comparison.md"""
import re, sys

PAT = re.compile(r"\\newcommand\{\\(\w+)\}\{(.*)\}$")
NUM = re.compile(r"[-+]?\d+(?:\{,\}\d{3})*(?:\.\d+)?(?:e-\d+)?")


def load(path):
    out = {}
    for line in open(path):
        mm = PAT.match(line.strip())
        if mm:
            out[mm.group(1)] = mm.group(2)
    return out


def nums(s):
    s = s.replace("\\times 10^{-", "e-")
    return [float(x.replace("{,}", "")) for x in NUM.findall(s)]


def flag(a, b):
    na, nb = nums(a), nums(b)
    if not na or not nb or len(na) != len(nb):
        return "" if a == b else "changed"
    worst = 0.0
    for x, y in zip(na, nb):
        if x == y:
            continue
        if x == 0 or y == 0 or (x > 0) != (y > 0):
            return "**sign/zero**"
        worst = max(worst, abs(y / x - 1))
    return f"**{100 * worst:.0f} %**" if worst > 0.10 else (f"{100 * worst:.0f} %" if worst > 0 else "")


if __name__ == "__main__":
    old = load(sys.argv[1]); new = load(sys.argv[2] if len(sys.argv) > 2 else "paper/generated/numbers.tex")
    keys = sorted(set(old) | set(new))
    rows = [(k, old.get(k, "—"), new.get(k, "—"), flag(old[k], new[k]) if k in old and k in new else "new" if k in new else "dropped")
            for k in keys]
    nflag = sum(1 for r in rows if r[3].startswith("**") or r[3] == "changed")
    L = ["## Before/after: every number the draft quotes (HONZA-88)", "",
         "Old = `paper/generated/numbers.tex` on `honza-77-manuscript` before the geometry fix; new = after the rebuild on raw "
         "Statcast 2026 coordinates. Change = largest relative change among the numbers inside the macro; **bold** = more "
         "than 10 % or a sign/zero change. Generated by `src/rebuild_comparison.py`.", "",
         f"{len(rows)} macros: {nflag} flagged, {sum(1 for r in rows if r[3] == '')} unchanged, "
         f"{sum(1 for r in rows if r[3] == 'new')} new.", "",
         "| Macro | Old | New | Change |", "|---|---|---|---|"]
    esc = lambda s: s.replace("|", "\\|")
    L += [f"| `{k}` | {esc(a)} | {esc(b)} | {f} |" for k, a, b, f in rows]
    open("results/rebuild_comparison.md", "w").write("\n".join(L) + "\n")
    print(len(rows), "macros;", nflag, "flagged")
